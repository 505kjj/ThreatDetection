import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

// https://www.unicode.org/Public/17.0.0/security/confusables.txt
const checksum = '091c7f82fc39ef208faf8f94d29c244de99254675e09de163160c810d13ef22a';
const input = readFileSync(process.argv[2]);
if (createHash('sha256').update(input).digest('hex') !== checksum) {
  throw new Error('Confusables source does not match the pinned Unicode 17.0.0 checksum');
}

const fromHex = value => String.fromCodePoint(...value.split(/\s+/).map(code => Number.parseInt(code, 16)));
const mappings = [];
for (const line of input.toString('utf8').split('\n')) {
  const record = line.split('#', 1)[0].trim();
  if (!record) continue;
  const [source, target] = record.split(';', 2).map(part => fromHex(part.trim()));
  // The registry uses ASCII aliases only. A non-ASCII source with a non-ASCII
  // mapping cannot contribute to an ASCII brand skeleton.
  if (/^[\x00-\x7f]$/.test(source) || /^[\x00-\x7f]+$/.test(target.normalize('NFD'))) {
    mappings.push(`  ${JSON.stringify(source)}: ${JSON.stringify(target)}`);
  }
}

writeFileSync(new URL('../vendor/confusables.mjs', import.meta.url),
  '// Generated by tools/generate-confusables.mjs from Unicode 17.0.0 confusables.txt.\n' +
  '// Copyright © 2025 Unicode, Inc. See unicode.LICENSE.txt.\n' +
  'export const confusables = {\n' + mappings.join(',\n') + '\n};\n');
